// Sets each SC voice's output level (voices/sc/sc-calibration.js) against the circuit model, by RMS over the first
// 300 ms of a hit:
//   SC_GAIN  [normal, accented]: at default knobs the SC voice is as loud as the circuit (normal and full-accent hits)
//   SC_TRIM  per knob, [dB at 0, dB at 1]: the circuit's level change at each end of the knob that the SC voice
//            doesn't make by itself (applied like the synth's knob trims, in Voice.knobGain, interpolated in dB)
//   node test/ref-render.mjs all     (the circuit renders, cached in test/.cache/)
//   node test/sc-calibrate.mjs [--write]   (run twice: the second pass refines the first)
import { writeFileSync } from 'node:fs';
import { VOICES } from '../dsp/kit.js';
import { SC_GAIN, SC_TRIM } from '../voices/sc/sc-calibration.js';
import { cases } from './match-lib.mjs';
import { circuitRender, scRender, rms, db } from './sc-lib.mjs';

const gains = {}, trims = {};
const r1 = (x) => Math.round(x * 10) / 10;
for (const [id] of VOICES) {
  const cs = cases(id), [n, a] = cs;
  const old = SC_GAIN[id] ?? [1, 1];
  const cN = rms(circuitRender(id, n)), sN = rms(scRender(id, n));
  const g = [old[0] * cN / sN, old[1] * rms(circuitRender(id, a)) / rms(scRender(id, a))];
  gains[id] = g.map((x) => Number(x.toPrecision(5)));
  const T = {};
  for (const c of cs) {
    const m = /^(.*)([01])$/.exec(c.name);
    if (!m || c.levelOnly) continue;
    const [, k, e] = m, prev = SC_TRIM[id]?.[k] ?? [0, 0];
    T[k] ??= prev.slice();
    T[k][+e] = r1(prev[+e] + db(rms(circuitRender(id, c)) / cN, rms(scRender(id, c)) / sN));
  }
  trims[id] = T;
  console.log(id.padEnd(3), `gain ${db(g[0], old[0]).toFixed(2)} / ${db(g[1], old[1]).toFixed(2)} dB`, JSON.stringify(T));
}
if (process.argv.includes('--write')) {
  const obj = (o) => Object.entries(o).map(([k, v]) => `${k}: [${v.join(', ')}]`).join(', ');
  writeFileSync(new URL('../voices/sc/sc-calibration.js', import.meta.url),
    `// Generated by test/sc-calibrate.mjs, against the circuit model (RMS over the first 300 ms of a hit).
// SC_GAIN: per SC voice [normal gain, accented gain], so that at default knobs it is as loud as the circuit.
// SC_TRIM: per knob [dB at 0, dB at 1], the circuit's level change at the knob's ends that the SC voice doesn't make.
export const SC_GAIN = {
${Object.entries(gains).map(([id, g]) => `  ${id}: [${g.join(', ')}],`).join('\n')}
};
export const SC_TRIM = {
${Object.entries(trims).map(([id, t]) => `  ${id}: { ${obj(t)} },`).join('\n')}
};
`);
  console.log('wrote voices/sc/sc-calibration.js');
}
