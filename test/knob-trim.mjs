// Measures, for every extra knob (PITCH, DECAY and the rest, see dsp/core.js
// knob()), how much louder or quieter the circuit gets at each end relative
// to its default hit, compares the synth voice, and writes the difference to
// dsp/knob-trim.js (the synth applies it in Voice.knobGain). Needs the
// circuit references: node test/ref-render.mjs all. Run it twice: the second
// pass refines on top of the first.
//   node test/knob-trim.mjs
import { writeFileSync } from 'node:fs';
import { Kit, VOICES } from '../dsp/kit.js';
import { KNOB_TRIM } from '../dsp/knob-trim.js';
import { cases, render } from './match-lib.mjs';
import { loadRef } from './match.mjs';
import { features } from './features.mjs';

const kit = new Kit(48000, { circuits: false });
const out = {};
for (const [id] of VOICES) {
  const extra = kit.behavioural[id].params.filter((p) => p.extra).map((p) => p.id);
  const cs = cases(id), n = cs.find((c) => c.name === 'n');
  const refN = loadRef(id, n); if (!refN) continue;
  const rv = (c) => features(loadRef(id, c)).vpp, gv = (c) => features(render(id, 'behavioural', c)).vpp;
  const rN = rv(n), gN = gv(n), T = {};
  for (const k of extra) {
    const old = KNOB_TRIM[id]?.[k] ?? [0, 0];
    T[k] = [0, 1].map((e, i) => {
      const c = cs.find((x) => x.name === k + e); if (!c || !loadRef(id, c)) return old[i];
      const d = 20 * Math.log10((rv(c) / rN) / (gv(c) / gN));
      return Math.round((old[i] + d) * 10) / 10;
    });
  }
  out[id] = T;
  console.log(id, JSON.stringify(T));
}
const body = Object.entries(out).map(([id, T]) => `  ${id}: { ${Object.entries(T).map(([k, v]) => `${k}: [${v.join(', ')}]`).join(', ')} },`).join('\n');
writeFileSync(new URL('../dsp/knob-trim.js', import.meta.url), `// Generated by test/knob-trim.mjs: the circuit's level change on each extra
// knob that the synth voice doesn't reproduce by itself, [dB at 0, dB at 1].
export const KNOB_TRIM = {
${body}
};
`);
